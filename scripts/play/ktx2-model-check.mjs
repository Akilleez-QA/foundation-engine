#!/usr/bin/env node
// scripts/play/ktx2-model-check.mjs (`npm run test:ktx2-browser`): a GLB with a KTX2 (Basis Universal) texture loads
// through the engine's model path, draws, reports its transcoded (compressed) resident bytes and disposes cleanly.
//
// Phases, each in a fresh page of the bench's muted, isolated Chromium:
//   1. dev, `?scene=plain`: a model without a KTX2 image. No request for the KTX2 chunk, KTX2Loader or the transcoder
//      files; `models.transcoderLoads` is 0.
//   2. dev, KTX2: the quad draws its four quadrant colours; the transcoder files are fetched once; the texture is a
//      compressed GPU format chosen by detectSupport on the pooled renderer; `compressedTextureMiB` equals its level
//      bytes. Then three cancel-after-transcode cycles (the #116 pattern): a candidate's transcode reply is held, the
//      candidate is despawned, the reply released; the late result is dropped and every resource it made disposed.
//      Then app disposal: every transcoder worker terminated, nothing resident.
//   3. dev, `?fallback=1`: the page hides every compressed-texture extension; the transcoder falls back to RGBA8, the
//      quad still draws, and the bytes are the RGBA8 level bytes.
//   4. production builds with `--base /sub/ktx2/` and `--base ./`, served only under a sub-path: the transcoder files
//      come from the build's hashed assets inside the sub-path; no request leaves it; no 4xx.
//
//   node --import tsx -r ./scripts/silent-browser.cjs scripts/play/ktx2-model-check.mjs [outDir]
//
// The fixture is generated by src/testing/ktx2-fixture.ts (hand-packed UASTC; see its provenance note).
// Limitations: desktop Chromium with SwiftShader software GL only; no physical device, phone GPU or driver memory.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync} from 'node:fs';
import {createServer as createHttpServer} from 'node:http';
import {tmpdir} from 'node:os';
import {extname, join, normalize, resolve, sep} from 'node:path';
import {build, createServer} from 'vite';
import {ROOT} from './lib.mjs';
import {launch} from '../perf/bench-browser.mjs';
import {decodePng} from '../perf/quality-png.mjs';
import {QUADRANTS, levelSides, quadGlb, quadrantKtx2} from '../../src/testing/ktx2-fixture.ts';

const out = resolve(process.argv[2] ?? 'playtest/ktx2-model');
mkdirSync(out, {recursive: true});
const beacon = readFileSync(join(ROOT, 'templates/mechanics/game/public/models/mechanics/beacon.glb'));
const quad = Buffer.from(quadGlb(quadrantKtx2(64)));
const glbs = {quad, 'quad-b': quad, plain: beacon};
const SIZE = 64,
  RGBA8_BYTES = levelSides(SIZE).reduce((n, s) => n + s * s * 4, 0),
  BLOCKS = levelSides(SIZE).reduce((n, s) => n + Math.ceil(s / 4) ** 2, 0);
const MIB = 1024 * 1024,
  RGBA_FORMAT = 1023; // THREE.RGBAFormat
const LAZY = /model-ktx2|KTX2Loader|basis_transcoder/;
const report = {
  revision: execFileSync('git', ['rev-parse', 'HEAD'], {cwd: ROOT, encoding: 'utf8'}).trim(),
  dirtyWorktree: !!execFileSync('git', ['status', '--porcelain'], {cwd: ROOT, encoding: 'utf8'}).trim(),
  fixture: {
    glbBytes: quad.length,
    ktx2: `${SIZE}×${SIZE} UASTC, ${levelSides(SIZE).length} levels`,
    rgba8Bytes: RGBA8_BYTES,
  },
  phases: {},
  passed: false,
  limitations: [
    'Desktop Chromium with SwiftShader software GL only: the compressed format chosen is the one SwiftShader exposes, not a phone GPU.',
    'Byte counts are the transcoded level bytes the engine estimates, not measured driver or GPU-process memory.',
    'Static hosting is a local sub-path server; no real CDN, Pages or itch.io upload.',
  ],
};
const save = () => writeFileSync(join(out, 'report.json'), JSON.stringify(report, null, 2) + '\n');

/** Network, console and page-error records for one page. */
function watch(page) {
  const rec = {requests: [], responses: [], errors: [], consoleErrors: []};
  page.on('request', r => rec.requests.push(r.url()));
  page.on('response', r => rec.responses.push({url: r.url(), status: r.status()}));
  page.on('pageerror', e => rec.errors.push(String(e)));
  page.on('console', m => {
    if (m.type() === 'error') rec.consoleErrors.push(m.text());
  });
  return rec;
}

const state = page => page.evaluate(() => window.ktx2Check.state());
const frames = (page, n = 2) =>
  page.evaluate(
    n =>
      new Promise(done => {
        const step = k => (k ? requestAnimationFrame(() => step(k - 1)) : done());
        step(n);
      }),
    n,
  );

/** Screenshot, then the colour at each quadrant centre (the quad fills most of the 800×600 view). */
async function quadrants(page, name) {
  const path = join(out, name + '.png');
  await page.screenshot({path});
  const png = decodePng(readFileSync(path)),
    at = (x, y) => {
      const i = (Math.round(y) * png.width + Math.round(x)) * 4;
      return [png.data[i], png.data[i + 1], png.data[i + 2]];
    };
  const cx = png.width / 2,
    cy = png.height / 2,
    d = Math.min(png.width, png.height) * 0.18;
  const seen = [at(cx - d, cy - d), at(cx + d, cy - d), at(cx - d, cy + d), at(cx + d, cy + d)];
  seen.forEach((rgb, i) =>
    rgb.forEach((v, c) =>
      assert.ok(
        Math.abs(v - QUADRANTS[i][c]) <= 16,
        `${name}: quadrant ${i} drew ${rgb.join(',')}, expected ${QUADRANTS[i].slice(0, 3).join(',')}`,
      ),
    ),
  );
  return {screenshot: path, quadrants: seen};
}

/** Waits for `fn(arg)` in the page; on a timeout, fails with the page's state and errors. */
async function until(page, rec, what, fn, arg) {
  try {
    await page.waitForFunction(fn, arg, {timeout: 30000});
  } catch (error) {
    const s = await state(page).catch(e => String(e));
    throw Error(`${what}: ${JSON.stringify({state: s, errors: rec.errors, console: rec.consoleErrors})}`, {
      cause: error,
    });
  }
}

/** Waits for the accepted model to be ready; on a timeout, fails with the page's state and errors. */
async function ready(page, rec, name) {
  try {
    await page.waitForFunction(() => window.ktx2Check.state().accepted === 'ready', null, {timeout: 30000});
  } catch (error) {
    const s = await state(page).catch(e => String(e));
    throw Error(
      `${name}: model not ready: ${JSON.stringify({state: s, errors: rec.errors, console: rec.consoleErrors})}`,
      {
        cause: error,
      },
    );
  }
}

async function openPage(browser, url) {
  const page = await browser.context.newPage();
  const rec = watch(page);
  await page.goto(url);
  try {
    await page.waitForFunction(() => window.ktx2Check?.booted === true, null, {timeout: 30000});
  } catch (error) {
    const failed = rec.responses.filter(r => r.status >= 400);
    throw Error(
      `${url}: page did not boot: ${JSON.stringify({errors: rec.errors, console: rec.consoleErrors, failed})}`,
      {
        cause: error,
      },
    );
  }
  return {page, rec};
}

const glbMiddleware = (prefix, served) => (req, res, next) => {
  const m = new RegExp(`^${prefix}__ktx2/(quad|quad-b|plain)\\.glb$`).exec((req.url ?? '').split('?')[0]);
  if (!m) return next?.() ?? false;
  served.push(m[1]);
  res.setHeader('Content-Type', 'model/gltf-binary');
  res.setHeader('Cache-Control', 'no-store');
  res.end(glbs[m[1]]);
  return true;
};

/** Phase 2's checks on a page showing the KTX2 quad; returns what it measured. */
async function drawnKtx2(page, rec, name, {fallback}) {
  await ready(page, rec, name);
  await frames(page, 3);
  const drawn = await quadrants(page, name);
  const s = await state(page),
    texture = await page.evaluate(() => window.ktx2Check.texture('initial'));
  assert.ok(texture?.compressed, `${name}: the template texture is a transcoded CompressedTexture`);
  assert.equal(texture.width, SIZE);
  assert.equal(texture.levels, levelSides(SIZE).length);
  if (fallback) {
    assert.equal(texture.format, RGBA_FORMAT, `${name}: no compressed format, so the transcoder chose RGBA8`);
    assert.equal(texture.bytes, RGBA8_BYTES);
  } else {
    assert.notEqual(texture.format, RGBA_FORMAT, `${name}: a compressed GPU format was chosen`);
    assert.ok([8, 16].includes(texture.bytes / BLOCKS), `${name}: whole 4×4 blocks of 8 or 16 bytes`);
  }
  assert.equal(s.models.compressedTextures, 1);
  assert.equal(Math.round(s.models.compressedTextureMiB * MIB), texture.bytes);
  assert.ok(s.models.residentMiB * MIB >= texture.bytes);
  assert.equal(s.models.transcoderLoads, 1);
  assert.ok(s.workers.created >= 1 && s.workers.created <= 2, `${name}: at most 2 transcoder workers`);
  const transcoder = rec.responses.filter(r => /basis_transcoder/.test(r.url));
  assert.equal(transcoder.length, 2, `${name}: basis_transcoder.js and .wasm fetched once each`);
  for (const r of transcoder) assert.equal(r.status, 200, r.url);
  return {...drawn, texture, models: s.models, workers: s.workers, transcoder};
}

async function disposed(page, name) {
  await page.evaluate(() => window.ktx2Check.dispose());
  await frames(page, 2);
  const s = await state(page);
  assert.equal(s.workers.live, 0, `${name}: every transcoder worker terminated with the app`);
  assert.equal(s.models.residentMiB, 0);
  assert.equal(s.models.compressedTextures, 0);
  assert.equal(s.models.cleanupFailures ?? 0, 0);
  return {workers: s.workers, models: s.models};
}

function clean(rec, name, allowConsole = []) {
  assert.deepEqual(rec.errors, [], `${name}: page errors`);
  const unexpected = rec.consoleErrors.filter(t => !allowConsole.some(re => re.test(t)));
  assert.deepEqual(unexpected, [], `${name}: console errors`);
}

let browser, server, staticHost;
const temps = [];
try {
  const served = [];
  const html = readFileSync(join(ROOT, 'scripts/play/fixtures/ktx2-site/index.html'), 'utf8').replace(
    '../ktx2-model-entry.mjs',
    '/scripts/play/fixtures/ktx2-model-entry.mjs',
  );
  server = await createServer({
    root: ROOT,
    logLevel: 'error',
    server: {host: '127.0.0.1', port: 0},
    plugins: [
      {
        name: 'ktx2-fixture',
        configureServer(s) {
          s.middlewares.use((req, res, next) => {
            if ((req.url ?? '').startsWith('/__ktx2.html')) {
              res.setHeader('Content-Type', 'text/html');
              res.end(html);
              return;
            }
            glbMiddleware('/', served)(req, res, next);
          });
        },
      },
    ],
  });
  await server.listen();
  const dev = server.resolvedUrls.local[0] + '__ktx2.html?flags=dev.silent';
  browser = await launch({width: 800, height: 600, strictClose: true});

  // 1. No KTX2 image: nothing KTX2 is requested.
  {
    const {page, rec} = await openPage(browser, dev + '&scene=plain');
    await ready(page, rec, 'plain');
    await frames(page, 3);
    const s = await state(page);
    const lazy = rec.requests.filter(u => LAZY.test(u));
    assert.deepEqual(lazy, [], 'a model without a KTX2 image requests no KTX2 chunk or transcoder file');
    assert.equal(s.models.transcoderLoads, 0);
    assert.equal(s.workers.created, 0);
    await page.screenshot({path: join(out, 'dev-plain.png')});
    report.phases.plain = {
      requests: rec.requests.filter(u => !u.startsWith('data:')).length,
      ktx2Requests: lazy,
      models: s.models,
      disposal: await disposed(page, 'plain'),
    };
    clean(rec, 'plain');
    await page.close();
  }

  // 2. KTX2 on the pooled renderer's compressed formats, three cancel-after-transcode cycles, disposal.
  {
    const {page, rec} = await openPage(browser, dev);
    const drawn = await drawnKtx2(page, rec, 'dev-ktx2', {fallback: false});
    const baseline = await state(page),
      cycles = [];
    for (let cycle = 1; cycle <= 3; cycle++) {
      const at = `cycle-${cycle}`;
      await page.evaluate(at => window.ktx2Check.arm(at), at);
      await page.evaluate(() => window.ktx2Check.spawnCandidate());
      await until(page, rec, `${at}: a transcode reply is held`, () => window.ktx2Check.state().held > 0);
      const before = await state(page);
      assert.equal(before.candidate, 'loading', `${at}: transcoded but not attached`);
      await page.evaluate(() => window.ktx2Check.cancelCandidate());
      // The scene's model owner retires the despawned entity's slot (aborting its lease) at its next frame sync.
      await frames(page, 2);
      await page.evaluate(() => window.ktx2Check.release());
      await until(
        page,
        rec,
        `${at}: the late result is dropped`,
        drops => window.ktx2Check.state().models.lateDrops > drops,
        before.models.lateDrops,
      );
      await frames(page, 2);
      const after = await state(page),
        released = await page.evaluate(at => window.ktx2Check.released(at), at);
      assert.equal(after.models.lateDrops, before.models.lateDrops + 1, `${at}: late result dropped`);
      assert.equal(after.models.disposed, before.models.disposed, `${at}: no uploaded template to dispose`);
      assert.equal(after.models.compressedTextures, 1, `${at}: only the accepted quad is resident`);
      assert.equal(after.models.residentMiB, baseline.models.residentMiB, `${at}: resident bytes unchanged`);
      assert.equal(after.models.instances, baseline.models.instances);
      assert.equal(after.models.cleanupFailures ?? 0, 0);
      assert.equal(after.models.transcoderLoads, 1, `${at}: the transcoder is set up once`);
      assert.ok(after.workers.live <= 2, `${at}: transcoder workers stay bounded`);
      assert.equal(released.parses, 1, `${at}: one late parse`);
      assert.equal(released.compressed, 1, `${at}: it held one transcoded texture`);
      assert.equal(released.released, released.resources, `${at}: every resource the late parse made was disposed`);
      cycles.push({cycle, before: before.models, after: after.models, released, workers: after.workers});
    }
    const quadB = served.filter(id => id === 'quad-b').length;
    assert.equal(quadB, 1, 'cycles 2 and 3 parse the retained file bytes');
    const transcoderAfter = rec.responses.filter(r => /basis_transcoder/.test(r.url)).length;
    assert.equal(transcoderAfter, 2, 'no transcoder refetch across cycles');
    report.phases.ktx2 = {...drawn, cycles, quadBFetches: quadB, disposal: await disposed(page, 'dev-ktx2')};
    clean(rec, 'dev-ktx2');
    await page.close();
  }

  // 3. No compressed format: the uncompressed RGBA8 fallback.
  {
    const {page, rec} = await openPage(browser, dev + '&fallback=1');
    const drawn = await drawnKtx2(page, rec, 'dev-fallback', {fallback: true});
    report.phases.fallback = {...drawn, disposal: await disposed(page, 'dev-fallback')};
    clean(rec, 'dev-fallback');
    await page.close();
  }
  save();

  // 4. Production builds under a sub-path: the transcoder files are hashed build assets inside it.
  const builds = [];
  staticHost = await new Promise(done => {
    const sites = new Map();
    const http = createHttpServer((req, res) => {
      const path = decodeURIComponent(new URL(req.url, 'http://x').pathname);
      const site = [...sites].find(([prefix]) => path.startsWith(prefix));
      if (!site) {
        res.statusCode = 404;
        res.end('outside the sub-path');
        return;
      }
      const [prefix, dir] = site;
      if (glbMiddleware(prefix, [])(Object.assign(req, {url: path}), res)) return;
      const file = normalize(join(dir, path.slice(prefix.length) || 'index.html'));
      if (!file.startsWith(dir + sep) || !existsSync(file) || !statSync(file).isFile()) {
        res.statusCode = 404;
        res.end('not found');
        return;
      }
      const types = {'.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.wasm': 'application/wasm'};
      res.setHeader('Content-Type', types[extname(file)] ?? 'application/octet-stream');
      res.end(readFileSync(file));
    });
    http.listen(0, '127.0.0.1', () =>
      done({
        origin: `http://127.0.0.1:${http.address().port}`,
        add: (prefix, dir) => sites.set(prefix, dir),
        close: () =>
          new Promise(r => {
            http.close(() => r());
            http.closeAllConnections();
          }),
      }),
    );
  });
  for (const [base, prefix] of [
    ['/sub/ktx2/', '/sub/ktx2/'],
    ['./', '/any/folder/'],
  ]) {
    const dir = mkdtempSync(join(tmpdir(), 'foundation-ktx2-build-'));
    temps.push(dir);
    await build({
      configFile: join(ROOT, 'vite.config.ts'),
      root: join(ROOT, 'scripts/play/fixtures/ktx2-site'),
      base,
      logLevel: 'error',
      build: {outDir: dir, emptyOutDir: true},
    });
    staticHost.add(prefix, dir);
    const name = `build-${base === './' ? 'relative' : 'subpath'}`;
    const {page, rec} = await openPage(browser, staticHost.origin + prefix + '?flags=dev.silent');
    const drawn = await drawnKtx2(page, rec, name, {fallback: false});
    const outside = rec.requests.filter(
      u => u.startsWith(staticHost.origin) && !u.startsWith(staticHost.origin + prefix),
    );
    assert.deepEqual(outside, [], `${name}: no request leaves ${prefix}`);
    const failed = rec.responses.filter(r => r.status >= 400);
    assert.deepEqual(failed, [], `${name}: no 4xx/5xx`);
    for (const r of drawn.transcoder)
      assert.match(new URL(r.url).pathname, new RegExp(`^${prefix}assets/basis_transcoder-[\\w-]+\\.(js|wasm)$`));
    builds.push({base, prefix, ...drawn, disposal: await disposed(page, name)});
    clean(rec, name);
    await page.close();
  }
  report.phases.builds = builds;
  report.passed = true;
  save();
  console.log(
    `ktx2 browser check: PASS · ${report.phases.ktx2.texture.bytes} B compressed (format ${report.phases.ktx2.texture.format}) vs ${RGBA8_BYTES} B RGBA8 fallback · 3 late drops · ${builds.length} sub-path builds → ${out}`,
  );
} catch (error) {
  report.error = String(error?.stack ?? error);
  save();
  console.error(`ktx2 browser check: FAIL → ${join(out, 'report.json')}`);
  throw error;
} finally {
  await browser?.close();
  await server?.close();
  await staticHost?.close();
  for (const dir of temps) rmSync(dir, {recursive: true, force: true});
}
