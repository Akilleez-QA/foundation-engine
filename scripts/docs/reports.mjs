const git = (args, root = ROOT) => execFileSync('git', args, {cwd: root, encoding: 'utf8', maxBuffer: 1 << 28});
const gitBytes = (args, root = ROOT) =>
  execFileSync('git', args, {cwd: root, maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore']});

export function parseArgs(argv) {
  const [command, ...rest] = argv;
  const options = {command, browser: []};
  for (let i = 0; i < rest.length; i++) {
    const arg = rest[i];
    if (!arg.startsWith('--')) throw Error(`Unexpected argument: ${arg}`);
    const key = arg.slice(2);
    if (key === 'no-gh' || key === 'trace') {
      options[key === 'trace' ? 'trace' : 'noGh'] = true;
      continue;
    }
    const value = rest[++i];
    if (value === undefined) throw Error(`${arg} needs a value`);
    if (key === 'browser') options.browser.push(value);
    else options[key] = value;
  }
  return options;
}

export function tapTotals(text) {
  const totals = {};
  for (const key of ['tests', 'suites', 'pass', 'fail', 'cancelled', 'skipped', 'todo', 'duration_ms']) {
    const matches = [...text.matchAll(new RegExp(`^# ${key} ([\\d.]+)$`, 'gm'))];
    if (matches.length) totals[key] = Number(matches.at(-1)[1]);
  }
  totals.failures = [...text.matchAll(/^not ok \d+ - (.+)$/gm)].map(m => m[1]);
  return totals;
}

export function changelogSection(text, version) {
  const lines = text.split('\n');
  const start = lines.findIndex(l => l.startsWith(`## ${version} `) || l === `## ${version}`);
  if (start < 0) return null;
  let end = lines.findIndex((l, i) => i > start && l.startsWith('## '));
  if (end < 0) end = lines.length;
  return {heading: lines[start].slice(3), lines: end - start};
}

export function digestRows(commit, root = ROOT) {
  return DIGEST_FILES.map(path => {
    let hash = 'absent at this commit';
    try {
      hash = createHash('sha256')
        .update(gitBytes(['show', `${commit}:${path}`], root))
        .digest('hex');
    } catch {}
    return {path, hash};
  });
}

const digestTable = rows => ['| File | SHA-256 |', '|---|---|', ...rows.map(r => `| \`${r.path}\` | \`${r.hash}\` |`)];

function ghIssues(state, noGh) {
  if (noGh) return null;
  try {
    const out = execFileSync(
      'gh',
      ['issue', 'list', '--state', state, '--limit', '500', '--json', 'number,title,labels'],
      {cwd: ROOT, encoding: 'utf8'},
    );
    return JSON.parse(out);
  } catch {
    return null;
  }
}

function header(title, id, version, commit, applies, up) {
  return [
    `# ${title}`,
    '',
    '| Field | Value |',
    '|---|---|',
    `| Document ID | ${id} |`,
    `| Version | ${version} |`,
    '| Status | Baselined |',
    '| Owner | Akilleez-QA |',
    `| Date | ${git(['show', '-s', '--format=%cs', commit]).trim()} |`,
    `| Baseline commit | \`${commit}\` |`,
    `| Applies to | ${applies} |`,
    `| Classification | Self-assessed Class E analog; not safety-critical (see [SMP §1](${up}plan/software-management-plan.md#1-software-classification-self-assessed)) |`,
    '',
    DISCLAIMER,
    '',
    `Generated by \`node scripts/docs/reports.mjs\`; do not edit by hand.`,
    '',
  ];
}

export function versionDescription({tag, prev, noGh}) {
  const commit = git(['rev-list', '-n', '1', tag]).trim();
  const tagDate = git(['for-each-ref', '--format=%(creatordate:short)', `refs/tags/${tag}`]).trim();
  const pkg = JSON.parse(git(['show', `${commit}:package.json`]));
  const files = git(['ls-tree', '-r', '--name-only', commit]).trim().split('\n');
  const tops = new Map();
  for (const f of files) {
    const top = f.includes('/') ? `${f.split('/')[0]}/` : f;
    tops.set(top, (tops.get(top) ?? 0) + 1);
  }
  const changelog = changelogSection(git(['show', `${commit}:CHANGELOG.md`]), pkg.version);
  const changes = prev ? git(['log', '--format=- %h %s', `${prev}..${tag}`]).trim() : '';
  const open = ghIssues('open', noGh);
  const out = header(
    `Foundation Engine version description ${tag}`,
    `FENGINE-VDD-${tag}`,
    '1.0',
    commit,
    `foundation-engine ${tag}`,
    '../',
  );
  out.push(
    '## 1. Identification',
    '',
    '| Item | Value |',
    '|---|---|',
    `| Name | ${pkg.name} |`,
    `| Package version | ${pkg.version} |`,
    `| Tag | \`${tag}\` (created ${tagDate}) |`,
    `| Commit | \`${commit}\` |`,
    `| License | ${pkg.license} |`,
    `| npm publication | ${pkg.private ? 'none (`private: true`)' : 'see registry'} |`,
    `| Node range | ${pkg.engines?.node ?? 'not declared'} |`,
    '',
    '## 2. Contents',
    '',
    `The tag contains ${files.length} tracked files. Top-level entries:`,
    '',
    '| Entry | Files |',
    '|---|---|',
    ...[...tops.entries()].sort().map(([k, v]) => `| \`${k}\` | ${v} |`),
    '',
    'The product is source. There is no binary artifact; GitHub Releases attach no files to this tag.',
    '',
    '## 3. Build and verification instructions',
    '',
    '```sh',
    `git clone https://github.com/Akilleez-QA/foundation-engine.git`,
    'cd foundation-engine',
    `git checkout ${tag}`,
    'npm ci',
    'npm test',
    'npm run build',
    '```',
    '',
    'Install with the npm that ships with Node 22 ([test plan §2.2](../verification/test-plan.md#22-local-reference-run-for-this-baseline)).',
    '',
    '## 4. Integrity',
    '',
    `Computed with \`git show ${tag}:<file> | sha256sum\`.`,
    '',
    ...digestTable(digestRows(commit)),
    '',
    '## 5. Changes',
    '',
    changelog
      ? `CHANGELOG section at the tag: "${changelog.heading}" (${changelog.lines} lines).`
      : `No CHANGELOG section for ${pkg.version} at the tag.`,
    '',
    prev
      ? `Commits since \`${prev}\`:`
      : 'This is the first tag in the repository; there is no previous version description.',
    '',
    ...(changes ? [changes, ''] : []),
    '## 6. Open problem reports and change requests',
    '',
    open === null
      ? 'Not queried (`--no-gh` or `gh` unavailable).'
      : `Open issues when this description was generated (${open.length}):`,
    '',
    ...(open ?? []).map(i => `- #${i.number} ${i.title}`),
    '',
    '## 7. Scans',
    '',
    'Test, lint and secret-scan results for documented baselines are in the [test reports](../verification/reports/README.md) and the [assurance record](../assurance/assurance-record.md).',
    '',
  );
  return out.join('\n');
}

export function testReport({label, commit, log, env, browser, noGh, trace: withTrace}) {
  const sha = git(['rev-parse', commit]).trim();
  const totals = tapTotals(readFileSync(log, 'utf8'));
  const trace = withTrace ? checkTrace(ROOT).info : null;
  const files = git(['ls-tree', '-r', '--name-only', sha]).trim().split('\n');
  const tests = files.filter(f => /\.test\.(?:ts|mjs)$|\.regression\.mjs$/.test(f));
  const sources = files.filter(f => f.startsWith('src/') && /\.(?:ts|mjs)$/.test(f) && !/\.test\./.test(f));
  let sourceLines = 0;
  for (const f of sources) sourceLines += git(['show', `${sha}:${f}`]).split('\n').length - 1;
  const open = ghIssues('open', noGh);
  const closed = ghIssues('closed', noGh);
  const out = header(
    `Foundation Engine test report ${label}`,
    `FENGINE-STR-${label}`,
    '1.0',
    sha,
    `foundation-engine at \`${sha.slice(0, 7)}\``,
    '../../',
  );
  const verdict = totals.fail === 0 && (totals.cancelled ?? 0) === 0 ? 'Pass' : 'Fail';
  out.push(
    '## 1. Overview',
    '',
    `Conclusion: **${verdict}** for the complete Node suite (\`npm test\`) at \`${sha}\`.`,
    `Environment: ${env ?? 'not recorded'}.`,
    '',
    '## 2. Node suite results',
    '',
    '| Measure | Value |',
    '|---|---|',
    `| Tests | ${totals.tests ?? 'n/a'} |`,
    `| Passed | ${totals.pass ?? 'n/a'} |`,
    `| Failed | ${totals.fail ?? 'n/a'} |`,
    `| Cancelled | ${totals.cancelled ?? 'n/a'} |`,
    `| Skipped | ${totals.skipped ?? 'n/a'} |`,
    `| Duration (ms) | ${totals.duration_ms ?? 'n/a'} |`,
    `| Log SHA-256 | \`${createHash('sha256').update(readFileSync(log)).digest('hex')}\` |`,
    '',
    totals.failures.length ? 'Failures:' : 'No failures.',
    '',
    ...totals.failures.map(f => `- ${f}`),
    ...(totals.failures.length ? [''] : []),
    '## 3. Browser checks',
    '',
  );
  if (!browser.length) out.push('None run for this report.', '');
  else {
    out.push('| Script | Result line | Log SHA-256 |', '|---|---|---|');
    for (const entry of browser) {
      const [name, path] = entry.split('=');
      const text = readFileSync(path, 'utf8');
      const pass = text
        .split('\n')
        .filter(l => /PASS|passed for/.test(l))
        .at(-1);
      const digest = createHash('sha256').update(readFileSync(path)).digest('hex');
      out.push(
        `| \`${name}\` | ${pass ? pass.replace(/\|/g, '\\|').replace(/\/[^\s)]+/g, '<path>') : 'no PASS line'} | \`${digest}\` |`,
      );
    }
    out.push('');
  }
  out.push(
    '## 4. Deviations',
    '',
    'Template gates, phone smoke and the browser scripts not listed in §3 were not run for this report; hosted CI runs them on code changes. Physical-device acceptance was not performed.',
    '',
    '## 5. Metrics',
    '',
    '| Metric | Value | Source |',
    '|---|---|---|',
    `| Tracked files | ${files.length} | \`git ls-tree -r\` |`,
    `| Test files | ${tests.length} | \`*.test.ts\`, \`*.test.mjs\`, \`*.regression.mjs\` |`,
    `| Source files under \`src/\` (excluding tests) | ${sources.length} | \`git ls-tree -r\` |`,
    `| Source lines under \`src/\` (excluding tests) | ${sourceLines} | newline count |`,
    ...(trace
      ? [
          `| Requirements | ${trace.requirements} | \`scripts/docs/check-trace.mjs\` on the documentation baseline |`,
          `| Requirements traced to verification | ${trace.traced} | same |`,
          `| Untested behavior gaps | ${trace.gaps} | same |`,
        ]
      : []),
    `| Open issues | ${open === null ? 'not queried' : open.length} | \`gh issue list --state open\` |`,
    `| Closed issues | ${closed === null ? 'not queried' : closed.length} | \`gh issue list --state closed\` |`,
    '',
  );
  return out.join('\n');
}

export function schemaFields(schema, prefix = '') {
  const rows = [];
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  for (const [name, item] of Object.entries(props)) {
    const path = prefix ? `${prefix}.${name}` : name;
    const range = [
      item.enum ? `one of ${item.enum.map(v => `\`${v}\``).join(', ')}` : '',
      'minimum' in item ? `>= ${item.minimum}` : '',
      'exclusiveMinimum' in item ? `> ${item.exclusiveMinimum}` : '',
      'maximum' in item ? `<= ${item.maximum}` : '',
    ]
      .filter(Boolean)
      .join(', ');
    rows.push({path, type: item.type ?? (item.enum ? 'string' : 'any'), required: required.has(name), range});
    if (item.type === 'object') rows.push(...schemaFields(item, path));
  }
  return rows;
}

export function toolsMarkdown() {
  const contract = JSON.parse(readFileSync(new URL('../../schemas/read-only-tools.json', import.meta.url), 'utf8'));
  const out = [`Tool inventory \`${contract.schema}\`, version ${contract.version}:`, ''];
  out.push('| Tool | Direction | Field | Type | Required | Range |', '|---|---|---|---|---|---|');
  for (const tool of contract.tools) {
    for (const row of schemaFields(tool.inputSchema))
      out.push(
        `| \`${tool.name}\` | input | \`${row.path}\` | ${row.type} | ${row.required ? 'yes' : 'no'} | ${row.range || 'n/a'} |`,
      );
    const output = tool.outputSchema;
    if (output.type === 'object')
      for (const row of schemaFields(output))
        out.push(
          `| \`${tool.name}\` | output | \`${row.path}\` | ${row.type} | ${row.required ? 'yes' : 'no'} | ${row.range || 'n/a'} |`,
        );
    else {
      const range = [
        'minimum' in output ? `>= ${output.minimum}` : '',
        'maximum' in output ? `<= ${output.maximum}` : '',
      ]
        .filter(Boolean)
        .join(', ');
      out.push(`| \`${tool.name}\` | output | (result) | ${output.type} | yes | ${range || 'n/a'} |`);
    }
  }
  out.push('');
  return out.join('\n');
}

export function digestsMarkdown({commit}) {
  const sha = git(['rev-parse', commit]).trim();
  return [`Digests at \`${sha}\`:`, '', ...digestTable(digestRows(sha)), ''].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const options = parseArgs(process.argv.slice(2));
  let text;
  if (options.command === 'vdd') text = versionDescription(options);
  else if (options.command === 'str') text = testReport(options);
  else if (options.command === 'digests') text = digestsMarkdown(options);
  else if (options.command === 'tools') text = toolsMarkdown();
  else
    throw Error(
      'Usage: reports.mjs vdd --tag <tag> [--prev <tag>] [--out <file>] [--no-gh]\n' +
        '       reports.mjs str --label <label> --commit <sha> --log <tap log> [--env <text>] [--browser name=log]... [--trace] [--out <file>] [--no-gh]\n' +
        '       reports.mjs digests --commit <sha>\n' +
        '       reports.mjs tools',
    );
  if (options.out) writeFileSync(options.out, text);
  else process.stdout.write(text);
}
